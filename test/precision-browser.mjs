import { createRequire } from 'node:module';
import fs from 'node:fs';
import assert from 'node:assert/strict';
const require = createRequire(import.meta.url);
const { chromium } = require(require.resolve('playwright', { paths: [process.env.PLAYWRIGHT_ROOT || process.cwd()] }));
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
const errors = []; page.on('pageerror', e => errors.push(e.message));
try {
  await page.goto(process.env.YELLOWJACKET_URL || 'http://127.0.0.1:8773/', { waitUntil: 'networkidle' });
  await page.getByRole('button', { name: 'DISMISS', exact: true }).click();
  await page.locator('#fileInput').setInputFiles('test/fixtures/spectrogram/berlin-30s.wav');
  await page.locator('#tabBtn-signal').click();
  await page.locator('#precisionInspector summary').click();
  await page.waitForFunction(() => document.querySelector('#precisionInspector [data-status]')?.textContent.startsWith('Ready.'));
  const host = page.locator('#precisionInspector');
  await host.locator('[name=fft]').selectOption('65536');
  await host.locator('[name=high]').fill('500');
  await host.locator('button[type=submit]').first().click();
  await page.waitForFunction(() => document.querySelector('#precisionInspector [data-status]').textContent.includes('none skipped'));
  const status = await host.locator('[data-status]').innerText();
  assert.match(status, /0.732 Hz/);
  await host.locator('[name=time]').fill('10'); await host.locator('[name=hz]').fill('100');
  await host.locator('[data-cursors] button[type=submit]').click();
  await host.locator('[name=time]').fill('20'); await host.locator('[name=hz]').fill('120');
  await host.locator('[data-cursors] button[type=submit]').click();
  const readout = await host.locator('[data-readout]').innerText(); assert.match(readout, /Δt/);
  const downloadPromise = page.waitForEvent('download'); await host.locator('[data-action=export]').click();
  const download = await downloadPromise; await download.saveAs('test/fixtures/spectrogram/measurements.csv');
  assert.equal(fs.readFileSync('test/fixtures/spectrogram/measurements.csv','utf8').trim().split('\n').length, 3);
  await host.locator('[name=axis]').selectOption('log');
  await host.locator('[name=floor]').fill('-90'); await host.locator('[name=floor]').blur();
  await host.screenshot({ path: 'test/fixtures/spectrogram/berlin-precision.png' });
  // Window edits invalidate old measurements. Invalid input must not resurrect them.
  await host.locator('[name=end]').fill('0.01'); await host.locator('button[type=submit]').first().click();
  assert.match(await host.locator('[data-status]').innerText(), /shorter/);
  assert.equal(await host.locator('[data-action=export]').isDisabled(), true);
  await host.locator('[name=end]').fill('30'); await host.locator('button[type=submit]').first().click();
  await host.locator('[data-action=cancel]').click();
  assert.match(await host.locator('[data-status]').innerText(), /cancelled/);
  await page.waitForTimeout(300);
  assert.match(await host.locator('[data-status]').innerText(), /cancelled/);
  await host.locator('button[type=submit]').first().click();
  await page.waitForFunction(() => document.querySelector('#precisionInspector [data-status]').textContent.includes('none skipped'));
  await page.setViewportSize({ width: 390, height: 844 });
  await host.screenshot({ path: 'test/fixtures/spectrogram/berlin-mobile.png' });
  assert.ok(await page.evaluate(() => document.querySelector('#precisionInspector').scrollWidth <= document.querySelector('#precisionInspector').clientWidth + 2));
  assert.deepEqual(errors, []);
  fs.writeFileSync('test/fixtures/spectrogram/browser-result.json', JSON.stringify({ status, readout, errors, checks: ['app file intake', 'worker analysis', 'absolute cursor measurement', 'CSV', 'log axis', 'contrast', 'stale invalidation', 'short passage refusal', 'cancellation', 'mobile width'] }, null, 2));
  console.log(status, '\n', readout, '\nBrowser precision checks passed.');
} finally { await browser.close(); }
